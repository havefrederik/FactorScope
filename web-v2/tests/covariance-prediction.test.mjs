function deterministicReturns() {
  let state = 123456789;
  const random = () => {
    state = (Math.imul(1664525, state) + 1013904223) >>> 0;
    return state / 4294967296;
  };
  const normal = () => Array.from({ length: 12 }, random).reduce((sum, value) => sum + value, 0) - 6;
  const rows = [];
  for (let period = 0; period < 700; period++) {
    const volatility = period < 300 ? .007 : period < 480 ? .018 : .010;
    const market = volatility * normal();
    const style = .006 * normal();
    const common = .003 * normal();
    rows.push([
      .9 * market + .3 * style + .004 * normal(),
      .65 * market - .5 * style + .0045 * normal(),
      1.2 * market + .15 * common + .005 * normal(),
      .35 * market + .8 * style + .005 * normal(),
      -.15 * market + .4 * common + .006 * normal(),
    ]);
  }
  return Array.from({ length: 5 }, (_, asset) => rows.map((row) => row[asset]));
}

