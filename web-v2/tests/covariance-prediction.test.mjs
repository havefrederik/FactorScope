test("CM-IEWMA matches covariance forecasts generated by the authors' Python package", () => {
  const returns = deterministicReturns();
  for (const [periodText, expected] of Object.entries(reference)) {
    const actual = forecastCombinedIewmaCovariance(returns, Number(periodText));
    const weights = actual.weights.map((expert) => expert.weight);
    const maxWeightError = Math.max(...weights.map((weight, index) => Math.abs(weight - expected.weights[index])));
    const maxCovarianceError = Math.max(...actual.covarianceMatrix.flatMap((row, i) => row.map((value, j) => Math.abs(value - expected.covariance[i][j]))));
    assert.ok(maxWeightError < 1e-4, `period ${periodText} weight error ${maxWeightError}`);
    assert.ok(maxCovarianceError < 1e-8, `period ${periodText} covariance error ${maxCovarianceError}`);
  }
});

