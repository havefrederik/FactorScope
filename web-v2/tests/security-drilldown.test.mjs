import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";

test("security drill-down connects holdings to transparent security analytics", async () => {
  const page = await readFile(new URL("../app/page.tsx", import.meta.url), "utf8");
  const analytics = await readFile(new URL("../lib/analytics.ts", import.meta.url), "utf8");
  const styles = await readFile(new URL("../app/globals.css", import.meta.url), "utf8");
  const decompositionComponent = page.slice(page.indexOf("function DecompositionChart"), page.indexOf("function DrawdownChart"));

  assert.match(page, /role="dialog"/);
  assert.match(page, /Analyze \$\{holding\.ticker\} security/);
  assert.match(page, /"Security Analysis"/);
  assert.match(page, /Select security for analysis/);
  assert.match(page, /Explore a portfolio holding/);
  assert.match(page, /SecurityAnalysisWorkspace/);
  assert.match(page, /SecurityAnalysisContent/);
  assert.match(page, /view !== "Security Analysis"/);
  assert.match(page, /Analyze →/);
  assert.match(page, /Systematic and idiosyncratic/);
  assert.match(page, /factor decomposition/);
  assert.match(page, /Individual factor contributions · exact daily reconciliation/);
  assert.match(page, /factor-level return decomposition/);
  assert.match(page, /RETURN COMPONENTS/);
  assert.match(page, /decomposition-end-labels/);
  assert.match(page, /decomposition-leader/);
  assert.match(decompositionComponent, /const indexes = Array\.from\(\{ length \}, \(_, index\) => index\);/);
  assert.match(decompositionComponent, /EACH BAR = CUMULATIVE THROUGH DATE/);
  assert.match(decompositionComponent, /Every vertical bar corresponds to one trading day/);
  assert.match(decompositionComponent, /const orderedComponents = components/);
  assert.match(decompositionComponent, /Math\.abs\(a\.value\) - Math\.abs\(b\.value\)/);
  assert.match(decompositionComponent, /a\.component\.key === "idiosyncratic"/);
  assert.match(decompositionComponent, /idiosyncratic contribution is always the outermost layer/);
  assert.match(decompositionComponent, /dateTickCount = spanDays <= 90 \? 7/);
  assert.match(decompositionComponent, /decomposition-date-axis/);
  assert.match(decompositionComponent, /96 \/ \(indexes\.length - 1\) \* \.9/);
  assert.match(decompositionComponent, /aria-pressed=\{displayMode==="stacked"\}/);
  assert.match(decompositionComponent, /aria-pressed=\{displayMode==="cumulative"\}/);
  assert.match(decompositionComponent, /onClick=\{\(\)=>setDisplayMode\("cumulative"\)\}/);
  assert.match(decompositionComponent, /decomposition-systematic-line/);
  assert.match(decompositionComponent, /decomposition-idio-line/);
  assert.doesNotMatch(decompositionComponent, /length \/ 190/);
  assert.doesNotMatch(decompositionComponent, /index % step/);
  assert.match(page, /systematicPoints/);
  assert.match(page, /PortfolioHoldings/);
  assert.match(analytics, /buildSecurityDrilldown/);
  assert.match(analytics, /dailyIdiosyncratic = securityReturns\.map/);
  assert.match(analytics, /value - dailyFactors\.reduce/);
  assert.match(analytics, /factors: factorDefs\.map/);
  assert.match(analytics, /rSquared/);
  assert.match(analytics, /idiosyncraticReturn/);
  assert.match(analytics, /type AnalysisWindow = number \| \{ startDate\?: string; endDate\?: string \}/);
  assert.match(page, /aria-label="Analysis start date"/);
  assert.match(page, /aria-label="Analysis end date"/);
  assert.doesNotMatch(page, /\[1,3,5\]\.map/);
  assert.match(styles, /\.decomp-factor-0\{fill:#22c55e\}/);
  assert.match(styles, /\.decomp-idio\{fill:#64748b\}/);
});
